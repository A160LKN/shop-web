import { plural } from './plural';

const forms = ['товар', 'товара', 'товаров'] as const;

it.each([
  [1, 'товар'],
  [2, 'товара'],
  [4, 'товара'],
  [5, 'товаров'],
  [11, 'товаров'],
  [12, 'товаров'],
  [14, 'товаров'],
  [21, 'товар'],
  [22, 'товара'],
  [111, 'товаров'],
  [0, 'товаров'],
])('%i %s', (n, expected) => {
  expect(plural(n, forms)).toBe(expected);
});
